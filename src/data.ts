// Helper to build a stop list along a straight-ish path between two coords.
function mkStops(
  stops: Array<[string, number, number, number, number, number?]>,
): Stop[] {
  return stops.map((s, i) => ({
    id: `s${i + 1}`,
    name: s[0],
    lat: s[1],
    lng: s[2],
    arrivalOffsetMin: s[3],
    departureOffsetMin: s[4],
    distanceKm: s[5],
  }));
}

